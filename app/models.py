class PlayerSeasonStats(db.Model):
    """Aggregated stats per player / competition / season. Layer 2 + 3."""
    __tablename__ = 'player_season_stats'
    id = db.Column(db.Integer, primary_key=True)
    player_id = db.Column(db.Integer, db.ForeignKey('players.id', ondelete='CASCADE'), nullable=False)
    team_id = db.Column(db.Integer, db.ForeignKey('teams.id'))
    competition_id = db.Column(db.Integer, db.ForeignKey('competitions.id'))
    season = db.Column(db.String(10), nullable=False)  # "2024-25"

    # Volume
    appearances = db.Column(db.Integer, default=0)
    starts = db.Column(db.Integer, default=0)
    minutes_played = db.Column(db.Integer, default=0)

    # Attack
    goals = db.Column(db.Integer, default=0)
    assists = db.Column(db.Integer, default=0)
    shots_total = db.Column(db.Integer, default=0)
    shots_on_target = db.Column(db.Integer, default=0)
    shot_accuracy_pct = db.Column(db.Numeric(5, 2))

    # Passing
    passes_total = db.Column(db.Integer, default=0)
    pass_accuracy_pct = db.Column(db.Numeric(5, 2))
    key_passes = db.Column(db.Integer, default=0)

    # Dribbles & duels
    dribbles_attempted = db.Column(db.Integer, default=0)
    dribbles_success = db.Column(db.Integer, default=0)
    duels_total = db.Column(db.Integer, default=0)
    duels_won = db.Column(db.Integer, default=0)
    aerial_duels_won = db.Column(db.Integer, default=0)

    # Discipline
    yellow_cards = db.Column(db.Integer, default=0)
    red_cards = db.Column(db.Integer, default=0)
    fouls_committed = db.Column(db.Integer, default=0)
    fouls_drawn = db.Column(db.Integer, default=0)

    # Advanced (Understat)
    xg = db.Column(db.Numeric(6, 3))
    xa = db.Column(db.Numeric(6, 3))
    npxg = db.Column(db.Numeric(6, 3))
    xg_chain = db.Column(db.Numeric(6, 3))
    xg_buildup = db.Column(db.Numeric(6, 3))

    # Per-90 (computed by worker)
    xg_per90 = db.Column(db.Numeric(5, 3))
    xa_per90 = db.Column(db.Numeric(5, 3))
    goals_per90 = db.Column(db.Numeric(5, 3))
    assists_per90 = db.Column(db.Numeric(5, 3))

    # FBref metrics (weekly scrape)
    progressive_carries = db.Column(db.Integer)
    progressive_passes_fbref = db.Column(db.Integer)
    pressures = db.Column(db.Integer)
    defensive_actions = db.Column(db.Integer)

    rating_avg = db.Column(db.Numeric(4, 2))

    source_base = db.Column(db.String(50), default='api-football')
    source_advanced = db.Column(db.String(50), default='understat')
    updated_at = db.Column(db.DateTime, default=lambda: datetime.now(timezone.utc))

    __table_args__ = (
        db.UniqueConstraint('player_id', 'competition_id', 'season', name='uq_player_season_comp'),
    )

    def __repr__(self):
        return f'<PlayerSeasonStats player={self.player_id} season={self.season}>'


