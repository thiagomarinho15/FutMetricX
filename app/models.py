class Player(db.Model):
    __tablename__ = 'players'
    id = db.Column(db.Integer, primary_key=True)
    # Core identity (legacy — kept for backward compat with existing workers)
    name = db.Column(db.String(120), nullable=False)
    nationality = db.Column(db.String(80))
    position = db.Column(db.String(50))        # GK | DEF | MID | ATT
    age = db.Column(db.Integer)
    team_id = db.Column(db.Integer, db.ForeignKey('teams.id'))
    source_id = db.Column(db.String(50))       # api-football player id
    source_name = db.Column(db.String(50))
    updated_at = db.Column(db.DateTime, default=lambda: datetime.now(timezone.utc))

    # Extended identity (Layer 1)
    name_full = db.Column(db.String(200))
    name_short = db.Column(db.String(100))
    nationality_iso2 = db.Column(db.String(2))
    date_of_birth = db.Column(db.Date)
    height_cm = db.Column(db.Integer)
    weight_kg = db.Column(db.Integer)
    foot_dominant = db.Column(db.String(10))   # left | right | both
    shirt_number = db.Column(db.Integer)
    contract_until = db.Column(db.Date)
    is_active = db.Column(db.Boolean, default=True)

    # External IDs for cross-source mapping
    external_id_understat = db.Column(db.Integer)
    external_id_transfermarkt = db.Column(db.String(50))
    external_id_fbref = db.Column(db.String(100))
    external_id_sportsdb = db.Column(db.String(50))

    # Photo assets (Layer 1 visual)
    photo_url_local = db.Column(db.String(500))          # CDN/local proxy (preferred)
    photo_url_apifootball = db.Column(db.String(500))
    photo_url_sportsdb_thumb = db.Column(db.String(500))
    photo_url_sportsdb_cutout = db.Column(db.String(500))

    # Bio (Layer 4 narrative)
    bio_text = db.Column(db.Text)   # crowd-sourced from TheSportsDB
    bio_llm = db.Column(db.Text)    # generated by LLM, updated monthly

    __table_args__ = (
        db.UniqueConstraint('source_id', 'source_name', name='uq_player_source'),
    )

    def __repr__(self):
        return f'<Player {self.name}>'


class Fixture(db.Model):
    __tablename__ = 'fixtures'
    id = db.Column(db.Integer, primary_key=True)
    competition_id = db.Column(db.Integer, db.ForeignKey('competitions.id'), nullable=False)
    home_team_id = db.Column(db.Integer, db.ForeignKey('teams.id'), nullable=False)
    away_team_id = db.Column(db.Integer, db.ForeignKey('teams.id'), nullable=False)
    scheduled_at = db.Column(db.DateTime)
    status = db.Column(db.String(20), default='scheduled')  # scheduled|live|finished|postponed
    home_score = db.Column(db.Integer)
    away_score = db.Column(db.Integer)
    source_primary = db.Column(db.String(50))
    source_id = db.Column(db.String(50))
    updated_at = db.Column(db.DateTime, default=lambda: datetime.now(timezone.utc))

    competition = db.relationship('Competition', backref='fixtures')
    home_team = db.relationship('Team', foreign_keys=[home_team_id])
    away_team = db.relationship('Team', foreign_keys=[away_team_id])

    __table_args__ = (
        db.UniqueConstraint('source_id', 'source_primary', name='uq_fixture_source'),
    )

    def __repr__(self):
        return f'<Fixture {self.home_team_id}x{self.away_team_id} {self.scheduled_at}>'


